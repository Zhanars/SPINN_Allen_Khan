"""Package the resubmission (revision 1) of symmetry-4596052.
usage: python package_r1.py
  -> submission/symmetry-4596052_R1_manuscript.zip   (the article in the MDPI Word template + the response to the reviewers, Word)
  -> submission/symmetry-4596052_R1_supporting_data.zip (raw results of revision 1, trained weights, reference solutions, scripts)"""
import os
import glob
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SUB = os.path.join(ROOT, "submission")


def add(z, path, arc):
    if os.path.isfile(path):
        z.write(path, arc)
        return 1
    return 0


def manuscript_zip():
    """one article only (manuscript_r1_mdpi.docx, MDPI Symmetry Word template) + the response to the reviewers (Word)"""
    out = os.path.join(SUB, "symmetry-4596052_R1_manuscript.zip")
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for f in ("manuscript_r1_mdpi.docx", "response_r1.docx"):
            n += add(z, os.path.join(HERE, f), f)
    print(out, n, "files", os.path.getsize(out) // 1024, "KB")


def data_zip():
    out = os.path.join(SUB, "symmetry-4596052_R1_supporting_data.zip")
    n = 0
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for sub in ("runs", "models", "ref"):
            for f in sorted(glob.glob(os.path.join(ROOT, "data_r1", sub, "*"))):
                n += add(z, f, f"data_r1/{sub}/" + os.path.basename(f))
        for f in sorted(glob.glob(os.path.join(ROOT, "data_r1", "*.*"))):
            if not f.endswith(".log"):
                n += add(z, f, "data_r1/" + os.path.basename(f))
        for f in ("experiment_2d.json", "symmetry_2d_multiseed.json", "stress_2d_sweep.json"):
            n += add(z, os.path.join(ROOT, "data", f), "data/" + f)
        for f in sorted(glob.glob(os.path.join(ROOT, "code", "*.py")) + glob.glob(os.path.join(ROOT, "code", "*.sh"))):
            n += add(z, f, "code/" + os.path.basename(f))
        z.writestr("README.txt",
                   "Supporting data of the revised manuscript symmetry-4596052 (revision 1).\n"
                   "data_r1/runs/<tag>.json : one record per training run (job settings, errors on the 200-point grid, max|u|, energy\n"
                   "                          increases at three time resolutions (vanilla PINN: one), energy-balance diagnostics and\n"
                   "                          penalty activity (Spectral-PINN only); inverse runs: estimate of eps, its trajectory and\n"
                   "                          the final losses).\n"
                   "data_r1/models/<tag>.pt : trained network weights (PyTorch state_dict).\n"
                   "data_r1/ref             : certified reference solutions on the evaluation grid (cached).\n"
                   "data_r1/classical*.json : classical Chebyshev solver, reaction-only ODE, classical inverse estimator, representation floors.\n"
                   "data_r1/numbers.json    : the value of every number macro used in the text of the article (not the table entries),\n"
                   "                          generated by code/make_tex_r1.py.\n"
                   "code/                   : r1_run.py <group> [nproc] runs a job group of r1_jobs.py and skips every job whose record is\n"
                   "                          already in data_r1/runs; only the groups 'all' and 'timing' are needed for the article (the\n"
                   "                          other groups are subsets of 'all' or contain unused jobs; make_tex_r1.py would pick up the\n"
                   "                          records of the unused jobs of variants, forward, ablation_lamE, penalty_regimes, stress_K\n"
                   "                          and stress_T). The first-version\n"
                   "                          2D scripts (run_experiments.py 2d, server_sweep_2d.py, stress_2d_sweep.py) overwrite the\n"
                   "                          files in data/. make_tex_r1.py and\n"
                   "                          make_figures_r1.py regenerate the numbers, tables and figures from data_r1 and data\n"
                   "                          (written to manuscript/r1_src and manuscript/figures_r1).\n"
                   "data/                   : two-dimensional results of the first version (Section 3.6, Tables 8 and 9).\n"
                   "Runs listed in data_r1/runs_workstation.txt were executed on an Intel Core i5-9400F workstation, all others on an\n"
                   "Intel Xeon Gold 6430 server (one CPU thread per run).\n")
    print(out, n, "files", os.path.getsize(out) // 1024, "KB")


