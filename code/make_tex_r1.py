"""Generate numbers_r1.tex (\\N{key} macros) and tables_r1.tex from data_r1.
Every number in the revised manuscript that comes from an experiment is produced here (no manual transcription).
usage: python make_tex_r1.py  -> manuscript/r1_src/numbers_r1.tex, manuscript/r1_src/tables_r1.tex, data_r1/numbers.json"""
import os
import re
import sys
import json
import glob
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import r1_tables as T

BS = chr(92)
OUT_DIR = os.path.join(HERE, "..", "manuscript", "r1_src")
NUM = {}


def tex_sci(x, d=2):
    """3.45e-4 -> 3.45\\times10^{-4}"""
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    m = x / 10 ** e
    if round(m, d) >= 10:
        m /= 10; e += 1
    return f"{m:.{d}f}{BS}times10^{{{e}}}"


def sci_pm(mean, sd, d=2):
    """(m +- s) x 10^e with the exponent of the mean."""
    if mean == 0:
        return "0"
    e = int(np.floor(np.log10(abs(mean))))
    if round(mean / 10 ** e, d) >= 10:
        e += 1
    return f"({mean / 10 ** e:.{d}f}{BS}pm{sd / 10 ** e:.{d}f}){BS}times10^{{{e}}}"


def fmt_stat(s, d=2):
    return "$" + sci_pm(s["mean"], s["sd"], d) + "$" if s["n"] > 1 else "$" + tex_sci(s["mean"], d) + "$"


def put(key, val):
    NUM[key] = val


def S(pattern):
    return T.summarize(pattern)


def nparams(K, hard, hidden=64):
    out = K - 1 if hard else K + 1
    return (1 * hidden + hidden) + (hidden * hidden + hidden) + (hidden * out + out)


# ------------------------------------------------------------------ classical / ODE
cl = json.load(open(os.path.join(HERE, "..", "data_r1", "classical.json")))
for ic in ("compat", "orig"):
    for eps in ("0.01", "0.1"):
        rec = cl[f"{ic}_eps{eps}"]
        put(f"ode.{ic}.{eps}.l2", "$" + tex_sci(rec["ode"]["1.0"]["l2"]) + "$")
        for c in rec["cheb"]:
            put(f"cheb.{ic}.{eps}.N{c['N']}.dt{c['dt']:g}.l2", "$" + tex_sci(c["l2"]) + "$")

if __name__ == "__main__":
    runs_dir = T.RUNS
    # ---- write numbers
    lines = [f"% generated by make_tex_r1.py -- do not edit", f"{BS}providecommand{{{BS}N}}[1]{{{BS}textbf{{??}}}}"]
    lines = ["% generated by make_tex_r1.py -- do not edit",
             BS + "makeatletter",
             BS + "newcommand{" + BS + "N}[1]{" + BS + "@ifundefined{num@#1}{" + BS + "textbf{??[#1]}}{" + BS + "csname num@#1" + BS + "endcsname}}",
             BS + "makeatother"]
    for k, v in sorted(NUM.items()):
        lines.append(BS + "expandafter" + BS + "def" + BS + "csname num@" + k + BS + "endcsname{" + v + "}")
    open(os.path.join(OUT_DIR, "numbers_r1.tex"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    json.dump(NUM, open(os.path.join(HERE, "..", "data_r1", "numbers.json"), "w"), indent=1)
    print(len(NUM), "numbers written")
